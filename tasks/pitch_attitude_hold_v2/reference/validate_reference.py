"""Independent checks of the version 2 reference and of the grader's truth model.

1. Linear models: the short period from each numerical Jacobian against the two state hand estimate.
2. The grader's scalar nonlinear model against environment/aircraft_model.derivatives, on random states.
3. Margins at each airspeed: the grader's exact delay sweep against python-control on a Pade delay.
4. Time step convergence: the nonlinear step response at 1 ms against 0.25 ms.
5. Linear against nonlinear at each airspeed: why the task's truth model is the nonlinear aircraft.
6. Feasibility: the steady elevator a +5 deg hold needs at each airspeed, and why the range starts at 20 m/s.

    python validate_reference.py         writes VALIDATION.md and two figures in this folder
"""
import json
import pathlib
import sys

import control as ct
import matplotlib
import numpy as np
from scipy.linalg import expm

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = pathlib.Path(__file__).resolve().parent
TASK = HERE.parent
sys.path.insert(0, str(TASK / "grader"))
sys.path.insert(0, str(TASK / "environment"))
import aircraft_model as am  # noqa: E402
import truth_model as tm  # noqa: E402

CTRL = json.loads((HERE / "controller.json").read_text(encoding="utf-8"))
SPEEDS = tm.SPEC["speeds_m_s"]


def pade_margins(plant, order=8):
    P = ct.ss(plant["A"], plant["B"], plant["C"], np.zeros((2, 1)))
    act = ct.tf([1.0], [tm.SPEC["tau_actuator_s"], 1.0])
    dl = ct.tf(*ct.pade(tm.SPEC["delay_s"], order))
    k_th = ct.tf([CTRL["K_p"], CTRL["K_i"]], [1.0, 0.0])
    gm, pm, _, _ = ct.margin((CTRL["K_q"] * ct.ss2tf(P[1, 0]) + k_th * ct.ss2tf(P[0, 0])) * act * dl)
    return 20 * np.log10(gm), pm


def linear_step(plant):
    """The same loop closed around the linear model (1 ms, exact discretization, limits on)."""
    spec = tm.SPEC
    dt, n = spec["dt_s"], int(round(spec["horizon_s"] / spec["dt_s"])) + 1
    nd = int(round(spec["delay_s"] / dt))
    A, B = plant["A"], plant["B"]
    M = expm(np.block([[A, B], [np.zeros((1, A.shape[0] + 1))]]) * dt)
    Phi, Gam = M[:4, :4], M[:4, 4:]
    de0 = plant["trim"]["delta_e_rad"]
    lim = np.radians(spec["position_limit_deg"])
    lo, hi = -lim - de0, lim - de0
    rate, tau, ref = np.radians(spec["rate_limit_deg_s"]), spec["tau_actuator_s"], np.radians(spec["step_deg"])
    x, integ, d = np.zeros(4), 0.0, 0.0
    theta, q, cmds = np.zeros(n), np.zeros(n), np.zeros(n)
    for k in range(n):
        theta[k], q[k] = x[3], x[2]
        j = k - nd
        th_m, q_m = (theta[j], q[j]) if j >= 0 else (0.0, 0.0)
        cmd = CTRL["K_p"] * (CTRL["b"] * ref - th_m) + CTRL["K_i"] * integ - CTRL["K_q"] * q_m
        integ += (ref - th_m) * dt
        cmds[k] = cmd
        rdot = min(max((min(max(cmd, lo), hi) - d) / tau, -rate), rate)
        x = Phi @ x + Gam[:, 0] * d
        d = min(max(d + rdot * dt, lo), hi)
    return {"t": np.arange(n) * dt, "theta": theta, "de_cmd": cmds, "de": cmds * 0, "airspeed": np.zeros(n),
            "sat_pos": np.zeros(n, bool), "sat_rate": np.zeros(n, bool), "ref": ref, "trim_de": de0,
            "diverged": False}


def main():
    out = ["# Validation of the version 2 reference", "",
           "Generated by `validate_reference.py`. Every number below comes from that script's run.", "",
           f"Reference gains, used at every airspeed: K_p = {CTRL['K_p']}, K_i = {CTRL['K_i']} 1/s, "
           f"K_q = {CTRL['K_q']} s, b = {CTRL['b']}.", ""]
    p = am.load_params()

    out += ["## 1. Linear models", "", "| Airspeed | Short period from the Jacobian | Hand estimate | Difference |",
            "|---|---|---|---|"]
    for V in SPEEDS:
        plant = tm.load_plant(V)
        (wn, z), _ = am.modes(plant["A"])
        wn_e, z_e = am.short_period_estimate(p, V, plant["trim"]["alpha_rad"])
        out.append(f"| {V:g} m/s | {wn:.3f} rad/s, damping {z:.3f} | {wn_e:.3f} rad/s, {z_e:.3f} | "
                   f"{100 * (wn_e / wn - 1):+.1f}% |")

    rng = np.random.default_rng(0)
    worst = 0.0
    for _ in range(5000):
        x = np.array([rng.uniform(15, 35), rng.uniform(-3, 5), rng.uniform(-1, 1), rng.uniform(-0.3, 0.4)])
        de, dth = rng.uniform(-0.5, 0.5), rng.uniform(0.2, 1.0)
        a = am.derivatives(p, x, [de, dth])
        b = np.array(tm.AIRCRAFT.derivatives(*x, de, dth))
        worst = max(worst, float(np.max(np.abs(a - b) / (1 + np.abs(a)))))
    out += ["", "## 2. The grader's nonlinear model", "",
            f"Largest relative difference from `aircraft_model.derivatives` over 5000 random states and inputs: "
            f"**{worst:.1e}**, rounding error.", ""]

    out += ["## 3. Stability margins, two methods", "",
            "| Airspeed | Grader: exact delay | python-control, eighth order Padé delay |", "|---|---|---|"]
    for V in SPEEDS:
        plant = tm.load_plant(V)
        m = tm.margins(plant, CTRL)
        gm, pm = pade_margins(plant)
        out.append(f"| {V:g} m/s | {m['gm_db']:.3f} dB, {m['pm_deg']:.3f} deg | {gm:.3f} dB, {pm:.3f} deg |")

    out += ["", "## 4. Time step convergence", "",
            "| Airspeed | Settling time, 1 ms / 0.25 ms (s) | Overshoot, 1 ms / 0.25 ms (%) | Largest pitch difference (deg) |",
            "|---|---|---|---|"]
    fine_spec = tm.SPEC | {"dt_s": 0.00025, "delay_s": 0.040}
    sims = {}
    for V in SPEEDS:
        coarse = tm.simulate(V, CTRL)
        fine = tm.simulate(V, CTRL, spec=fine_spec)
        mc, mf = tm.step_metrics(coarse), tm.step_metrics(fine, fine_spec)
        diff = np.degrees(np.max(np.abs(coarse["theta"] - fine["theta"][::4][:len(coarse["theta"])])))
        sims[V] = coarse
        out.append(f"| {V:g} m/s | {mc['settling_time_s']:.3f} / {mf['settling_time_s']:.3f} | "
                   f"{mc['overshoot_pct']:.2f} / {mf['overshoot_pct']:.2f} | {diff:.4f} |")

    out += ["", "## 5. Linear model against the nonlinear aircraft", "",
            "| Airspeed | Settling time, linear / nonlinear (s) | Peak elevator, linear / nonlinear (deg) | Lowest airspeed in the step (m/s) |",
            "|---|---|---|---|"]
    for V in SPEEDS:
        ml = tm.step_metrics(linear_step(tm.load_plant(V)) | {"airspeed": np.array([V])})
        mn = tm.step_metrics(sims[V])
        out.append(f"| {V:g} m/s | {ml['settling_time_s']:.3f} / {mn['settling_time_s']:.3f} | "
                   f"{ml['max_elevator_deg']:.2f} / {mn['max_elevator_deg']:.2f} | {mn['min_airspeed_m_s']:.2f} |")
    out += ["", "At low speed the airspeed decays during the step, so the elevator loses effectiveness and the "
            "nonlinear response is slower than the linear model predicts. A design verified only on the linear "
            "models misjudges its own settling time.", ""]

    out += ["## 6. Why the range starts at 20 m/s", "",
            "The steady elevator needed to hold +5 deg at fixed throttle, from each linear model's DC gain:", "",
            "| Airspeed | Trim elevator (deg) | Change for +5 deg (deg) | Absolute (deg) |", "|---|---|---|---|"]
    for V in (18.0, 20.0, 25.0, 32.0):
        x0, u0, _ = am.trim_level(p, V)
        A, B = am.linearize(p, x0, u0)
        g0 = float(np.real(ct.dcgain(ct.ss(A, B[:, [0]], [[0, 0, 0, 1.0]], [[0.0]]))))
        dde = np.radians(tm.SPEC["step_deg"]) / g0
        out.append(f"| {V:g} m/s | {np.degrees(u0[0]):.2f} | {np.degrees(dde):+.2f} | "
                   f"{np.degrees(u0[0] + dde):.2f} |")
    out += ["", "At 18 m/s the hold would need more than the 25 deg stop, whatever the gains: the step is physically "
            "out of reach there. At 20 m/s it needs about 21 deg, which leaves a few degrees for the transient.", ""]

    fig, ax = plt.subplots(2, 1, figsize=(7.0, 5.2), sharex=True)
    for V, s in sims.items():
        ax[0].plot(s["t"], np.degrees(s["theta"]), lw=1.5, label=f"{V:g} m/s")
        ax[1].plot(s["t"], np.degrees(s["de_cmd"] + s["trim_de"]), lw=1.2, label=f"{V:g} m/s")
    step = tm.SPEC["step_deg"]
    ax[0].axhspan(step * 0.98, step * 1.02, color="0.85", label="2% band")
    ax[0].set_ylabel("pitch attitude change (deg)")
    ax[1].axhline(-tm.SPEC["position_limit_deg"], color="0.3", lw=0.8, ls=":")
    ax[1].set_ylabel("elevator command (deg)")
    ax[1].set_xlabel("time (s)")
    for a in ax:
        a.grid(True, alpha=0.4)
        a.legend(loc="lower right", fontsize=8)
        a.set_xlim(0, 10)
    fig.tight_layout()
    fig.savefig(HERE / "step_response.png", dpi=150)

    w = np.logspace(-2, 2.5, 4000)
    fig, ax = plt.subplots(2, 1, figsize=(7.0, 5.2), sharex=True)
    for V in SPEEDS:
        L = tm.loop_response(tm.load_plant(V), CTRL, w)
        ax[0].semilogx(w, 20 * np.log10(np.abs(L)), label=f"{V:g} m/s")
        ax[1].semilogx(w, np.degrees(np.unwrap(np.angle(L))), label=f"{V:g} m/s")
    ax[0].axhline(0, color="0.4", lw=0.8)
    ax[1].axhline(-180, color="0.4", lw=0.8)
    ax[0].set_ylabel("|L| (dB)")
    ax[1].set_ylabel("phase (deg)")
    ax[1].set_xlabel("frequency (rad/s)")
    for a in ax:
        a.grid(True, which="both", alpha=0.4)
        a.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(HERE / "loop_bode.png", dpi=150)

    (HERE / "VALIDATION.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
