"""Independent checks of the reference solution and of the grader's truth model.

1. Linear model: the short period from the numerical Jacobian against the classical two state approximation.
2. Margins: the grader's exact delay sweep against python-control's stability_margins on a Pade approximation.
3. Time response: the grader's fixed step simulation (limits off) against python-control's forced_response of
   the closed loop with a Pade delay. Nothing in 3 is shared with the grader except the plant matrices.
4. Linear validity: the same controller, actuator and delay closed around the nonlinear longitudinal model.

    python validate_reference.py         writes VALIDATION.md and three figures in this folder
"""
import json
import pathlib
import sys

import control as ct
import matplotlib
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = pathlib.Path(__file__).resolve().parent
TASK = HERE.parent
sys.path.insert(0, str(TASK / "grader"))
sys.path.insert(0, str(TASK / "environment"))
import aircraft_model as am  # noqa: E402
import truth_model as tm  # noqa: E402

PLANT = tm.load_plant()
CTRL = json.loads((HERE / "controller.json").read_text(encoding="utf-8"))
SPEC = tm.SPEC


def pade_loop(order=8):
    """The loop broken at the elevator command, built from python-control blocks."""
    P = ct.ss(PLANT["A"], PLANT["B"], PLANT["C"], np.zeros((2, 1)))
    act = ct.tf([1.0], [SPEC["tau_actuator_s"], 1.0])
    dl = ct.tf(*ct.pade(SPEC["delay_s"], order))
    k_th = ct.tf([CTRL["K_p"], CTRL["K_i"]], [1.0, 0.0])
    return (CTRL["K_q"] * ct.ss2tf(P[1, 0]) + k_th * ct.ss2tf(P[0, 0])) * act * dl


def closed_loop_pade(order=8):
    """Closed loop from theta_cmd to theta with setpoint weight b, no limits, Pade delay on both measurements."""
    s = ct.tf("s")
    P = ct.ss(PLANT["A"], PLANT["B"], PLANT["C"], np.zeros((2, 1)))
    act = ct.tf([1.0], [SPEC["tau_actuator_s"], 1.0])
    dl = ct.tf(*ct.pade(SPEC["delay_s"], order))
    G_th, G_q = ct.ss2tf(P[0, 0]), ct.ss2tf(P[1, 0])
    # delta_e = (K_p b + K_i/s) r - (K_p + K_i/s) D theta - K_q D q, with theta = G_th Act delta_e, q = G_q Act delta_e
    forward = CTRL["K_p"] * CTRL["b"] + CTRL["K_i"] / s
    loop = ((CTRL["K_p"] + CTRL["K_i"] / s) * G_th + CTRL["K_q"] * G_q) * act * dl
    return ct.minreal(forward * act * G_th / (1 + loop), verbose=False)


def nonlinear_step():
    """Closed loop on the nonlinear longitudinal model, same controller, actuator, limits and delay."""
    p = am.load_params()
    x0, u0, _ = am.trim_level(p, PLANT["trim"]["airspeed_m_s"])
    dt, n = SPEC["dt_s"], int(round(SPEC["horizon_s"] / SPEC["dt_s"])) + 1
    nd = int(round(SPEC["delay_s"] / dt))
    ref = np.radians(SPEC["step_deg"])
    lim, rate = np.radians(SPEC["position_limit_deg"]), np.radians(SPEC["rate_limit_deg_s"])
    x, d, integ = x0.copy(), 0.0, 0.0
    theta = np.zeros(n)
    hist = []
    for k in range(n):
        hist.append(x.copy())
        theta[k] = x[3] - x0[3]
        j = k - nd
        th_m, q_m = (hist[j][3] - x0[3], hist[j][2]) if j >= 0 else (0.0, 0.0)
        cmd = CTRL["K_p"] * (CTRL["b"] * ref - th_m) + CTRL["K_i"] * integ - CTRL["K_q"] * q_m
        integ += (ref - th_m) * dt
        target = min(max(cmd, -lim - u0[0]), lim - u0[0])
        rdot = min(max((target - d) / SPEC["tau_actuator_s"], -rate), rate)
        inp = np.array([u0[0] + d, u0[1]])
        k1 = am.derivatives(p, x, inp)                       # RK4, elevator held over the step
        k2 = am.derivatives(p, x + dt / 2 * k1, inp)
        k3 = am.derivatives(p, x + dt / 2 * k2, inp)
        k4 = am.derivatives(p, x + dt * k3, inp)
        x = x + dt / 6 * (k1 + 2 * k2 + 2 * k3 + k4)
        d = min(max(d + rdot * dt, -lim - u0[0]), lim - u0[0])
    return theta, np.array(hist)


def main():
    lines = ["# Validation of the reference solution", "",
             "Generated by `validate_reference.py`. Every number below comes from that script's run.", "",
             f"Reference gains: K_p = {CTRL['K_p']}, K_i = {CTRL['K_i']} 1/s, K_q = {CTRL['K_q']} s, "
             f"b = {CTRL['b']}.", ""]

    # 1. linear model against the hand estimate
    alpha = PLANT["trim"]["alpha_rad"]
    wn_est, z_est = am.short_period_estimate(am.load_params(), PLANT["trim"]["airspeed_m_s"], alpha)
    (wn_sp, z_sp), (wn_ph, z_ph) = am.modes(PLANT["A"])
    lines += ["## 1. Linear model", "",
              "| Mode | From the Jacobian | Hand estimate | Difference |", "|---|---|---|---|",
              f"| Short period frequency (rad/s) | {wn_sp:.3f} | {wn_est:.3f} | {100 * (wn_est / wn_sp - 1):+.1f}% |",
              f"| Short period damping | {z_sp:.3f} | {z_est:.3f} | {100 * (z_est / z_sp - 1):+.1f}% |",
              f"| Phugoid frequency (rad/s) | {wn_ph:.4f} | {np.sqrt(2) * 9.81 / 25.0:.4f} (Lanchester) | "
              f"{100 * (np.sqrt(2) * 9.81 / 25.0 / wn_ph - 1):+.1f}% |", "",
              "The two state short period estimate uses only C_L_alpha, C_D, C_m_alpha and C_m_q. Lanchester's "
              "phugoid estimate neglects drag and the speed dependence of thrust, so only rough agreement is "
              "expected.", ""]

    # 2. margins, two ways
    mg = tm.margins(PLANT, CTRL)
    gm_ct, pm_ct, wpc, wgc = ct.margin(pade_loop(8))
    lines += ["## 2. Stability margins, two methods", "",
              "| Method | Gain margin (dB) | Phase margin (deg) | Crossover (rad/s) |", "|---|---|---|---|",
              f"| Grader: exact delay, 200001 point sweep | {mg['gm_db']:.3f} | {mg['pm_deg']:.3f} | "
              f"{mg['crossover_rad_s'][0]:.3f} |",
              f"| python-control margin(), eighth order Padé delay | {20 * np.log10(gm_ct):.3f} | {pm_ct:.3f} | "
              f"{wgc:.3f} |", ""]

    # 3. time response, two ways (no limits: the reference never reaches them)
    sim_lin = tm.simulate(PLANT, CTRL, limits=False)
    sim_lim = tm.simulate(PLANT, CTRL)
    T = closed_loop_pade(8)
    t = sim_lin["t"]
    _, y_ct = ct.forced_response(T, t, np.full_like(t, np.radians(SPEC["step_deg"])))
    diff_ct = np.degrees(np.max(np.abs(y_ct - sim_lin["theta"])))
    diff_lim = np.degrees(np.max(np.abs(sim_lim["theta"] - sim_lin["theta"])))
    met = tm.step_metrics(sim_lim)
    lines += ["## 3. Step response, two simulators", "",
              f"- Largest difference in pitch attitude between the grader's simulation and python-control's "
              f"forced_response (eighth order Padé delay): **{diff_ct:.4f} deg** on a 5 deg step.",
              f"- Largest difference between the grader's simulation with and without the rate and position "
              f"limits: **{diff_lim:.4f} deg**. The reference never reaches either limit (rate limited for "
              f"{met['rate_limited_s']:.3f} s).",
              f"- Metrics: overshoot {met['overshoot_pct']:.2f}%, 2% settling time {met['settling_time_s']:.3f} s, "
              f"peak absolute elevator command {met['max_elevator_deg']:.2f} deg.", ""]

    # 4. nonlinear check
    th_nl, hist = nonlinear_step()
    diff_nl = np.degrees(np.max(np.abs(th_nl - sim_lim["theta"])))
    u_drop = hist[0][0] - np.min(hist[:, 0])
    lines += ["## 4. Linear model validity", "",
              f"The same loop closed around the nonlinear longitudinal model (fourth order Runge-Kutta, 1 ms): the largest pitch "
              f"attitude difference from the linear truth model over 20 s is **{diff_nl:.4f} deg** on the 5 deg "
              f"step, and the body axis speed drops by {u_drop:.2f} m/s. The linear model is adequate for this "
              "step size.", ""]

    # figures
    fig, ax = plt.subplots(2, 1, figsize=(7.0, 5.2), sharex=True)
    ax[0].plot(t, np.degrees(sim_lim["theta"]), lw=1.6, label="truth model (linear, limits on)")
    ax[0].plot(t, np.degrees(th_nl), "--", lw=1.2, label="nonlinear model")
    ax[0].axhspan(SPEC["step_deg"] * 0.98, SPEC["step_deg"] * 1.02, color="0.85", label="2% band")
    ax[0].axvline(met["settling_time_s"], color="0.4", lw=0.8, ls=":")
    ax[0].set_ylabel("pitch attitude change (deg)")
    ax[0].legend(loc="lower right", fontsize=8)
    ax[1].plot(t, np.degrees(sim_lim["de_cmd"] + sim_lim["trim_de"]), lw=1.4, label="command")
    ax[1].plot(t, np.degrees(sim_lim["de"] + sim_lim["trim_de"]), lw=1.0, label="surface")
    ax[1].set_ylabel("elevator (deg)")
    ax[1].set_xlabel("time (s)")
    ax[1].legend(loc="lower right", fontsize=8)
    for a in ax:
        a.grid(True, alpha=0.4)
        a.set_xlim(0, 8)
    fig.tight_layout()
    fig.savefig(HERE / "step_response.png", dpi=150)

    w = np.logspace(-2, 2.5, 4000)
    L = tm.loop_response(PLANT, CTRL, w)
    fig, ax = plt.subplots(2, 1, figsize=(7.0, 5.2), sharex=True)
    ax[0].semilogx(w, 20 * np.log10(np.abs(L)))
    ax[0].axhline(0, color="0.4", lw=0.8)
    ax[0].set_ylabel("|L| (dB)")
    ax[1].semilogx(w, np.degrees(np.unwrap(np.angle(L))))
    ax[1].axhline(-180, color="0.4", lw=0.8)
    ax[1].set_ylabel("phase (deg)")
    ax[1].set_xlabel("frequency (rad/s)")
    for a in ax:
        a.grid(True, which="both", alpha=0.4)
    fig.tight_layout()
    fig.savefig(HERE / "loop_bode.png", dpi=150)

    (HERE / "VALIDATION.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
